import {chromium} from 'playwright';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
try{
 const page=await browser.newPage({viewport:{width:1366,height:900}}),errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:19682/');
 await page.waitForSelector('.login-toggle');
 await page.click('.login-toggle');
 const user='duck'+Date.now().toString().slice(-9);
 await page.locator('[aria-label=Username]').fill(user);
 await page.locator('[aria-label=Password]').fill('test-password-123');
 await page.locator('[aria-label="Confirm password"]').fill('test-password-123');
 await page.locator('.login-form button[type=submit]').click();
 await page.waitForFunction(()=>window.desktopLab?.session?.kind==='registered',null,{timeout:30000});
 await page.locator('[aria-label=Applications]').click();
 await page.getByRole('menuitem',{name:'Games'}).click();
 await page.getByRole('menuitem',{name:'Physics games (XR planned)'}).click();
 await page.getByRole('menuitem',{name:'Microduck',exact:true}).click();
 await page.waitForSelector('.window-content.microduck-app',{timeout:30000});
 await page.waitForFunction(()=>document.querySelector('[data-brf=app-status]')?.textContent==='Project open.',null,{timeout:90000});
 await page.locator('[data-brf=show-simple-duck]').click();
 await page.waitForFunction(()=>/Simple duck, step 0/.test(document.querySelector('[data-brf=schematic-status]')?.textContent??''));
 await page.locator('[data-brf=target-value]').fill('0.25');await page.locator('[data-brf=target-set]').click();
 await page.waitForFunction(()=>/Target request accepted/.test(document.querySelector('[data-brf=target-feedback]')?.textContent??''));
 await page.getByRole('button',{name:'Hardware tuning mode'}).click();await page.getByRole('button',{name:'Game mode'}).click();
 await page.locator('[data-brf=step]').click();
 await page.waitForFunction(()=>/step 1/.test(document.querySelector('[data-brf=schematic-status]')?.textContent??''),null,{timeout:30000});
 await page.getByRole('button',{name:'Save to My files'}).click();
 await page.getByRole('dialog',{name:'Choose folder in My files'}).getByRole('button',{name:'Use this folder'}).click();
 await page.waitForFunction(()=>document.body.textContent.includes('Saved locally:'),null,{timeout:30000});
 await page.getByRole('button',{name:'Open from My files'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Continue'}).click();
 await page.getByRole('dialog',{name:'Choose from My files'}).getByRole('button',{name:'Choose file Microduck.brf'}).click();
 await page.waitForFunction(()=>/session-targets-/.test(document.querySelector('[data-brf=saved-records]')?.textContent??''),null,{timeout:30000});
 await page.waitForFunction(()=>document.querySelector('[data-brf=app-status]')?.textContent==='Project open.',null,{timeout:30000});
 const saved=await page.locator('[data-brf=saved-records]').textContent();
 if(!saved.includes('0.25'))throw Error('Saved target missing: '+saved);
 if(errors.length)throw Error('Page errors '+JSON.stringify(errors));
 console.log(JSON.stringify({browser:browser.version(),status:'passed',step:1,saved,errors}));
}finally{await browser.close()}
